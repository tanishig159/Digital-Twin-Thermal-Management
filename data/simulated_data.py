# Cooling Analytics Calculations
# -----------------------------------------------------------------------------
def get_cooling_analytics_metrics(current_record: Dict[str, Any]) -> Dict[str, Any]:
    """
    Derives engineering cooling performance metrics from current operational state.
    """
    fan1 = current_record.get("fan_1_rpm", 3450)
    fan2 = current_record.get("fan_2_rpm", 3320)
    inlet_t = current_record.get("inlet_temp", 24.5)
    outlet_t = current_record.get("outlet_temp", 38.2)
    delta_t = round(outlet_t - inlet_t, 1)
    airflow_cfm = current_record.get("chassis_airflow_cfm", 42.0)
    heat_dissipated = current_record.get("total_heat_dissipation_w", 218.0)

    # Air mass flow rate estimate: 1 CFM ~ 0.000566 kg/s at STP
    mass_flow_kg_s = airflow_cfm * 0.000566
    cp_air = 1005.0  # J/(kg*K)
    # Measured thermal dissipation from air stream: Q = m_dot * cp * delta_T
    q_air_stream = round(mass_flow_kg_s * cp_air * delta_t, 1)

    # Thermal resistance R_th = delta_T / Q (K/W)
    thermal_resistance = round(delta_t / max(heat_dissipated, 1.0), 3)

    # Cooling Effectiveness (Dimensionless COP estimate)
    # Electrical power drawn by dual fans: approx 15W - 35W depending on RPM
    fan_power_w = 12.0 + 20.0 * ((fan1 + fan2) / 9000.0)**2.5
    cooling_cop = round(heat_dissipated / max(fan_power_w, 5.0), 2)

    return {
        "fan_1_rpm": fan1,
        "fan_2_rpm": fan2,
        "inlet_temp": inlet_t,
        "outlet_temp": outlet_t,
        "delta_t": delta_t,
        "airflow_cfm": airflow_cfm,
        "mass_flow_kg_s": round(mass_flow_kg_s, 4),
        "heat_dissipated_w": heat_dissipated,
        "air_absorbed_heat_w": q_air_stream,
        "thermal_resistance_k_w": thermal_resistance,
        "fan_electrical_power_w": round(fan_power_w, 1),
        "cooling_cop": cooling_cop,
        "cooling_status": "ACTIVE - NOMINAL" if delta_t < 18.0 else "ACTIVE - HIGH THERMAL LOAD",
    }


