# Component Thermal Status & Telemetry
# -----------------------------------------------------------------------------
def get_current_component_metrics(
    ambient_temp: float = 25.0,
    load_multiplier: float = 1.0,
    cooling_factor: float = 1.0,
    fluctuation_seed: Optional[int] = None,
) -> pd.DataFrame:
    """
    Returns current snapshot of all components with temperatures, limits, and status.
    """
    rng = np.random.default_rng(fluctuation_seed if fluctuation_seed is not None else int(datetime.now().timestamp()) % 10000)
    data = []

    for comp_id, comp in COMPONENTS.items():
        fluct = rng.normal(0.0, 0.6)
        # Scaled temperature
        temp = ambient_temp + (comp.nominal_temp_c - 25.0) * (load_multiplier / (cooling_factor**0.6)) + fluct
        temp = round(float(temp), 1)

        # Status evaluation
        if temp >= comp.max_rating_c:
            status = "CRITICAL"
            status_color = "#ef4444"
        elif temp >= comp.warning_threshold_c:
            status = "WARNING"
            status_color = "#f59e0b"
        else:
            status = "NORMAL"
            status_color = "#10b981"

        margin = round(comp.max_rating_c - temp, 1)

        data.append({
            "id": comp.id,
            "component": comp.name,
            "short_name": comp.short_name,
            "category": comp.category,
            "temperature_c": temp,
            "warning_threshold_c": comp.warning_threshold_c,
            "max_rating_c": comp.max_rating_c,
            "margin_c": margin,
            "status": status,
            "status_color": status_color,
            "power_w": round(comp.nominal_power_w * load_multiplier, 1),
            "pos_x": comp.center[0],
            "pos_y": comp.center[1],
        })

    df = pd.DataFrame(data)
    return df.sort_values(by="temperature_c", ascending=False).reset_index(drop=True)


