# Historical & Real-time Telemetry Series
# -----------------------------------------------------------------------------
def generate_historical_telemetry(
    n_points: int = 60,
    interval_seconds: int = 60,
    end_time: Optional[datetime] = None,
    seed: int = 101,
) -> pd.DataFrame:
    """
    Generates realistic historical time series telemetry for the past N intervals.
    Includes simulated workload variation, diurnal ambient shift, and fan response.
    """
    if end_time is None:
        end_time = datetime.now()

    start_time = end_time - timedelta(seconds=(n_points - 1) * interval_seconds)
    timestamps = [start_time + timedelta(seconds=i * interval_seconds) for i in range(n_points)]

    rng = np.random.default_rng(seed)
    time_steps = np.arange(n_points)

    # Workload profile with steady-state, transient load steps, and recovery
    load_profile = 1.0 + 0.15 * np.sin(time_steps / 8.0) + 0.08 * np.sin(time_steps / 2.5)
    # Inject a realistic step increase around step 35-45
    load_profile[32:48] += 0.22

    # Ambient temperature slight fluctuation (24.0 to 25.5 C)
    ambient_series = 24.5 + 0.8 * np.sin(time_steps / 15.0) + rng.normal(0, 0.1, n_points)

    # Fan RPM response follows workload with a slight lag
    base_fan_rpm = 3100.0
    fan_1_rpm = base_fan_rpm + (load_profile - 1.0) * 1400.0 + rng.normal(0, 25, n_points)
    fan_2_rpm = base_fan_rpm * 0.95 + (load_profile - 1.0) * 1350.0 + rng.normal(0, 25, n_points)
    fan_1_rpm = np.clip(fan_1_rpm, 1800, 4800)
    fan_2_rpm = np.clip(fan_2_rpm, 1700, 4600)

    # Cooling factor derived from fan speeds
    cooling_factor = ((fan_1_rpm + fan_2_rpm) / (2.0 * base_fan_rpm))**0.5

    data: Dict[str, Any] = {
        "timestamp": timestamps,
        "ambient_temp": np.round(ambient_series, 2),
        "fan_1_rpm": np.round(fan_1_rpm, 0).astype(int),
        "fan_2_rpm": np.round(fan_2_rpm, 0).astype(int),
        "cooling_intensity_pct": np.round((fan_1_rpm / 4800.0) * 100.0, 1),
        "chassis_airflow_cfm": np.round(28.0 + (fan_1_rpm / 4800.0) * 26.0, 1),
    }

    # Generate component telemetry with physical thermal inertia (first-order lag)
    for comp_id, comp in COMPONENTS.items():
        temps = np.zeros(n_points)
        current_t = comp.nominal_temp_c

        # Physical time constant tau in intervals
        tau = 3.5 if comp_id in ["cpu", "vrm"] else 6.0

        for t in range(n_points):
            target_t = ambient_series[t] + (comp.nominal_temp_c - 24.5) * (load_profile[t] / (cooling_factor[t]**0.6))
            noise = rng.normal(0, 0.25)
            current_t += (1.0 / tau) * (target_t - current_t) + noise
            temps[t] = current_t

        data[f"{comp_id}_temp"] = np.round(temps, 1)

    df = pd.DataFrame(data)

    # Air inlet / outlet temps
    df["inlet_temp"] = df["ambient_temp"]
    total_power = sum(c.nominal_power_w for c in COMPONENTS.values()) * load_profile
    df["total_heat_dissipation_w"] = np.round(total_power, 1)
    # delta_T = Q / (m_dot * Cp)
    df["delta_t_inlet_outlet"] = np.round(total_power / (df["chassis_airflow_cfm"] * 1.5), 1)
    df["outlet_temp"] = np.round(df["inlet_temp"] + df["delta_t_inlet_outlet"], 1)

    # Calculate max temperature across all components per row
    comp_temp_cols = [f"{c}_temp" for c in COMPONENTS]
    df["max_component_temp"] = df[comp_temp_cols].max(axis=1)
    df["avg_component_temp"] = np.round(df[comp_temp_cols].mean(axis=1), 1)

    return df


def simulate_telemetry_step(last_row: pd.Series, step_seconds: int = 10, noise_scale: float = 0.4) -> Dict[str, Any]:
    """
    Computes a realistic single step progression for live telemetry updates.
    """
    rng = np.random.default_rng()
    new_timestamp = last_row["timestamp"] + timedelta(seconds=step_seconds)

    # Small drift in ambient
    new_ambient = float(np.clip(last_row["ambient_temp"] + rng.normal(0, 0.05), 22.0, 30.0))

    # Fan RPM slight adjustment
    new_fan1 = int(np.clip(last_row["fan_1_rpm"] + rng.integers(-40, 45), 2000, 4700))
    new_fan2 = int(np.clip(last_row["fan_2_rpm"] + rng.integers(-35, 40), 1900, 4500))

    cooling_factor = ((new_fan1 + new_fan2) / (2.0 * 3100.0))**0.5
    airflow_cfm = round(28.0 + (new_fan1 / 4800.0) * 26.0, 1)

    step_data: Dict[str, Any] = {
        "timestamp": new_timestamp,
        "ambient_temp": round(new_ambient, 2),
        "fan_1_rpm": new_fan1,
        "fan_2_rpm": new_fan2,
        "cooling_intensity_pct": round((new_fan1 / 4800.0) * 100.0, 1),
        "chassis_airflow_cfm": airflow_cfm,
    }

    comp_temps = []
    for comp_id, comp in COMPONENTS.items():
        prev_temp = last_row[f"{comp_id}_temp"]
        # Slow return towards target with random noise
        target = new_ambient + (comp.nominal_temp_c - 24.5) / (cooling_factor**0.5)
        new_val = prev_temp + 0.12 * (target - prev_temp) + rng.normal(0, noise_scale)
        new_val = round(float(np.clip(new_val, 30.0, 110.0)), 1)
        step_data[f"{comp_id}_temp"] = new_val
        comp_temps.append(new_val)

    step_data["inlet_temp"] = round(new_ambient, 1)
    total_power = sum(c.nominal_power_w for c in COMPONENTS.values()) * (1.0 + rng.normal(0, 0.04))
    step_data["total_heat_dissipation_w"] = round(float(total_power), 1)
    step_data["delta_t_inlet_outlet"] = round(float(total_power / (airflow_cfm * 1.5)), 1)
    step_data["outlet_temp"] = round(step_data["inlet_temp"] + step_data["delta_t_inlet_outlet"], 1)

    step_data["max_component_temp"] = max(comp_temps)
    step_data["avg_component_temp"] = round(float(np.mean(comp_temps)), 1)

    return step_data


