# What-If Simulation Demonstrator
# -----------------------------------------------------------------------------
def simulate_what_if_scenario(
    heat_load_w: float = 210.0,
    ambient_temp_c: float = 25.0,
    cooling_intensity_pct: float = 70.0,
    convection_coeff_h: float = 35.0,
) -> Dict[str, Any]:
    """
    Computes an illustrative thermal response under user-modified operating conditions.
    NOTE: This is a fast illustrative engineering demonstration model, not a certified FEA solver.
    """
    # Nominal reference state
    ref_total_power = sum(c.nominal_power_w for c in COMPONENTS.values())  # ~218W
    load_ratio = heat_load_w / ref_total_power
    cooling_ratio = max(cooling_intensity_pct, 5.0) / 70.0  # Normalized to 70% nominal cooling
    h_ratio = max(convection_coeff_h, 5.0) / 35.0  # Normalized to 35 W/m2K

    # Compute modified component temperatures
    simulated_comps = []
    custom_temps = {}
    hotspot_count = 0

    for comp_id, comp in COMPONENTS.items():
        # Component power scaled proportionally
        p_comp = comp.nominal_power_w * load_ratio
        
        # Convective thermal resistance: R_conv ~ 1 / (h * A * (v_air)^0.6)
        thermal_resistance_scaling = (1.0 / (h_ratio**0.45)) * (1.0 / (cooling_ratio**0.55))
        
        # Temperature rise: Delta_T = Power * R_eff
        nominal_delta_t = comp.nominal_temp_c - 25.0
        new_delta_t = nominal_delta_t * (load_ratio) * thermal_resistance_scaling
        new_temp = round(ambient_temp_c + new_delta_t, 1)

        custom_temps[comp_id] = new_temp

        if new_temp >= comp.max_rating_c:
            status = "CRITICAL"
            hotspot_count += 1
        elif new_temp >= comp.warning_threshold_c:
            status = "WARNING"
            hotspot_count += 1
        else:
            status = "NORMAL"

        baseline_temp = comp.nominal_temp_c
        delta_from_baseline = round(new_temp - baseline_temp, 1)

        simulated_comps.append({
            "id": comp_id,
            "component": comp.name,
            "short_name": comp.short_name,
            "baseline_temp_c": baseline_temp,
            "simulated_temp_c": new_temp,
            "delta_c": delta_from_baseline,
            "warning_threshold_c": comp.warning_threshold_c,
            "max_rating_c": comp.max_rating_c,
            "margin_c": round(comp.max_rating_c - new_temp, 1),
            "status": status,
        })

    sim_df = pd.DataFrame(simulated_comps)

    # Generate the corresponding 2D spatial heatmap field
    x_mesh, y_mesh, temp_field = generate_enclosure_thermal_field(
        ambient_temp=ambient_temp_c,
        load_multiplier=load_ratio,
        cooling_factor=cooling_ratio,
        convection_h=convection_coeff_h,
        custom_component_temps=custom_temps,
        add_noise=False,
    )

    max_temp = float(np.max(temp_field))
