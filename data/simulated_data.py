# 2D Spatial Thermal Simulation (Field Heatmap)
# -----------------------------------------------------------------------------
def generate_enclosure_thermal_field(
    ambient_temp: float = 25.0,
    load_multiplier: float = 1.0,
    cooling_factor: float = 1.0,
    convection_h: float = 35.0,
    custom_component_temps: Optional[Dict[str, float]] = None,
    nx: int = 75,
    ny: int = 50,
    add_noise: bool = True,
    seed: int = 42,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Simulates a 2D engineering thermal field over the electronic chassis.
    Combines Gaussian heat dissipation from components with forced convective
    drift from the left inlet (x=0) to the right exhaust (x=300).
    """
    rng = np.random.default_rng(seed)

    x = np.linspace(0.0, CHASSIS_WIDTH_MM, nx)
    y = np.linspace(0.0, CHASSIS_HEIGHT_MM, ny)
    X, Y = np.meshgrid(x, y)

    # Base air temperature rises gradually from inlet (left) to outlet (right)
    # Airflow enters at ambient_temp and absorbs dissipated heat
    airflow_temp_rise = 12.0 * (load_multiplier / max(cooling_factor, 0.2)) * (35.0 / max(convection_h, 5.0))**0.4
    convective_drift = (X / CHASSIS_WIDTH_MM) * airflow_temp_rise
    temp_grid = np.full_like(X, ambient_temp) + convective_drift

    # Add thermal influence of each component
    for comp_id, comp in COMPONENTS.items():
        cx, cy = comp.center

        if custom_component_temps and comp_id in custom_component_temps:
            target_peak = custom_component_temps[comp_id]
            delta_t = target_peak - ambient_temp
        else:
            # Physics-inspired scaling with heat load and convection
            power = comp.nominal_power_w * load_multiplier
            # Thermal resistance inversely proportional to cooling and convection
            eff_r_th = (1.0 / (comp.thermal_sigma_mm * 0.15)) * (1.0 / (cooling_factor**0.6)) * (35.0 / convection_h)**0.5
            delta_t = power * eff_r_th * 0.35 + (comp.nominal_temp_c - 25.0) * (load_multiplier / cooling_factor)**0.5

        sigma_x = comp.thermal_sigma_mm * (1.0 + 0.35 * (X - cx) / CHASSIS_WIDTH_MM)  # Airflow elongation to the right
        sigma_y = comp.thermal_sigma_mm * 0.9

        # Asymmetric Gaussian kernel simulating forced convection sweep
        dist_x = X - cx
        dist_y = Y - cy
        
        # Elongation in downstream direction (x > cx)
        downstream_factor = np.where(dist_x >= 0, 1.35, 0.85)
        exponent = -(dist_x**2 / (2 * (sigma_x * downstream_factor)**2) + dist_y**2 / (2 * sigma_y**2))
        
        comp_field = delta_t * np.exp(np.clip(exponent, -30, 0))
        temp_grid += comp_field

    # Add realistic boundary cooling (heat loss through aluminum enclosure walls)
    wall_loss = 0.8 * (np.sin(np.pi * X / CHASSIS_WIDTH_MM) * np.sin(np.pi * Y / CHASSIS_HEIGHT_MM))
    temp_grid = ambient_temp + (temp_grid - ambient_temp) * (0.85 + 0.15 * wall_loss)

    # Optional subtle turbulence noise for realistic telemetry feel
    if add_noise:
        noise = rng.normal(0.0, 0.25, size=temp_grid.shape)
        temp_grid += noise

    return x, y, temp_grid


